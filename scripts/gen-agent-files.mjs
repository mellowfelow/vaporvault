// Generates every domain-bearing / agent-ready file from src/config/site.js.
// Never hand-edit the output of this script — edit the config and re-run.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITE, RULES, CATEGORIES, BRANDS } from '../src/config/site.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const pub = join(root, 'public');
const domain = SITE.domain;
const base = `https://${domain}`;

function write(relPath, content) {
  const full = join(pub, relPath);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content, 'utf-8');
}

// A — robots.txt is generated by src/app/robots.js (Next.js native), not here.

